def generate_spec(node, indent=0):
    spec = []
    indent_str = "  " * indent
    
    # Node header
    node_name = f'"{node["name"]}"' if node.get("name") else ""
    spec.append(f"{indent_str}=== {node['type']} {node_name} {node['id']} ===")
    
    # Basic properties
    layout = node.get("layout", {})
    dims = layout.get("dimensions", {})
    loc = layout.get("locationRelativeToParent", {})
    
    spec.append(f"{indent_str}X Position: {loc.get('x', 'N/A')}")
    spec.append(f"{indent_str}Y Position: {loc.get('y', 'N/A')}")
    spec.append(f"{indent_str}Width: {dims.get('width', 'N/A')}")
    spec.append(f"{indent_str}Height: {dims.get('height', 'N/A')}")
    spec.append(f"{indent_str}Rotation: 0")
    spec.append(f"{indent_str}Opacity: 1")
    spec.append(f"{indent_str}Constraints: N/A")
    
    # Auto Layout properties
    if layout.get("mode") in ["row", "column"]:
        spec.append(f"{indent_str}Auto Layout Direction: {layout['mode']}")
        spec.append(f"{indent_str}Gap: {layout.get('gap', 'N/A')}")
        
        padding = layout.get("padding")
        if padding:
            # Parse padding (e.g., "15px 26px" or "10px 20px 30px 40px")
            parts = str(padding).split()
            if len(parts) == 1:
                spec.append(f"{indent_str}Padding Top: {parts[0]}")
                spec.append(f"{indent_str}Padding Bottom: {parts[0]}")
                spec.append(f"{indent_str}Padding Left: {parts[0]}")
                spec.append(f"{indent_str}Padding Right: {parts[0]}")
            elif len(parts) == 2:
                spec.append(f"{indent_str}Padding Top: {parts[0]}")
                spec.append(f"{indent_str}Padding Bottom: {parts[0]}")
                spec.append(f"{indent_str}Padding Left: {parts[1]}")
                spec.append(f"{indent_str}Padding Right: {parts[1]}")
            elif len(parts) == 4:
                spec.append(f"{indent_str}Padding Top: {parts[0]}")
                spec.append(f"{indent_str}Padding Right: {parts[1]}")
                spec.append(f"{indent_str}Padding Bottom: {parts[2]}")
                spec.append(f"{indent_str}Padding Left: {parts[3]}")
        
        spec.append(f"{indent_str}Horizontal Alignment: {layout.get('justifyContent', 'N/A')}")
        spec.append(f"{indent_str}Vertical Alignment: {layout.get('alignItems', 'N/A')}")
        
        sizing = layout.get("sizing", {})
        spec.append(f"{indent_str}Horizontal Resize Mode: {sizing.get('horizontal', 'N/A')}")
        spec.append(f"{indent_str}Vertical Resize Mode: {sizing.get('vertical', 'N/A')}")
    
    # Fill
    if node.get("fills"):
        spec.append(f"{indent_str}Fill: {node['fills']}")
    
    # Stroke
    if node.get("strokes"):
        spec.append(f"{indent_str}Stroke: {node['strokes']}")
    if node.get("strokeWeight"):
        spec.append(f"{indent_str}Stroke Weight: {node['strokeWeight']}")
    
    # Corner Radius
    if node.get("borderRadius"):
        spec.append(f"{indent_str}Corner Radius: {node['borderRadius']}")
    
    # Shadow
    spec.append(f"{indent_str}Shadow: None")
    
    # Blur
    spec.append(f"{indent_str}Blur: None")
    
    # Text-specific properties
    if node["type"] == "TEXT":
        text_style = node.get("textStyle", {})
        spec.append(f"{indent_str}--- Text Properties ---")
        spec.append(f"{indent_str}Text Content: {node.get('text', 'N/A')}")
        spec.append(f"{indent_str}Font Family: {text_style.get('fontFamily', 'N/A')}")
        spec.append(f"{indent_str}Font Weight: {text_style.get('fontWeight', 'N/A')}")
        spec.append(f"{indent_str}Font Size: {text_style.get('fontSize', 'N/A')}")
        spec.append(f"{indent_str}Line Height: {text_style.get('lineHeight', 'N/A')}")
        spec.append(f"{indent_str}Letter Spacing: {text_style.get('letterSpacing', 'N/A')}")
    
    # Image-specific properties
    if node["type"] in ["IMAGE-SVG", "RECTANGLE"] and isinstance(node.get("fills"), dict) and node["fills"].get("type") == "IMAGE":
        spec.append(f"{indent_str}--- Image Properties ---")
        spec.append(f"{indent_str}Fill Mode: {node['fills'].get('scaleMode', 'N/A')}")
        spec.append(f"{indent_str}Object Fit: {node['fills'].get('objectFit', 'N/A')}")
    
    spec.append("")  # Empty line between nodes
    
    # Recursively process children
    if "children" in node:
        for child in node["children"]:
            spec.extend(generate_spec(child, indent + 1))
    
    return spec


